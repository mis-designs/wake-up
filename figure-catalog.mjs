export function normalizeFigureId(value) {
  const clean = String(value ?? '').normalize('NFKC').trim().split(/[?#]/, 1)[0].replace(/\\/g, '/');
  const match = clean.split('/').pop().match(/^(?:fig[\s_-]*)?0*(\d+)(?:\.[a-z0-9]+)?$/i);
  const number = match && Number(match[1]);
  return Number.isSafeInteger(number) && number > 0 ? `fig${number}` : '';
}

export function getFigureDetail(value) {
  return FIGURE_CATALOG[normalizeFigureId(value)] || null;
}
